--!strict
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local NetStream = require(ReplicatedStorage:WaitForChild("Netstream"))
assert(NetStream.GetVersion() == "4.1.1")
NetStream.Configure({BitFrameMaxBytes = 1024, BandwidthGovernorEnabled = false, CompressionEnabled = false, TransportFastFlushEnabled = false, HandshakeEnabled = false})
local oversized = NetStream.Event("__NSOversizedFrame", {Id = 35220, Compression = false})
local valid = NetStream.Event("__NSFrameRecovery", {Id = 35221, Compression = false})
local ack = NetStream.Event("__NSFrameAck", {Id = 35222, Compression = false})
valid:Connect(function(player, value)
	assert(value == 123, "Valid frame after error was corrupted")
	local stats = NetStream.GetStats()
	assert(stats.BitFrameTailPaddingRejected >= 1, "Extra zero byte padding was accepted")
	assert(stats.DecodeErrors >= 1, "Malformed packet was not counted")
	assert(ack:FireClient(player, stats.BitFrameTailPaddingRejected), "Failed to acknowledge recovery")
end)
oversized:Connect(function() error("Oversized payload unexpectedly reached server") end)
print("NetStream 4.1.1 BitFrame failure / padding regression server ready")
