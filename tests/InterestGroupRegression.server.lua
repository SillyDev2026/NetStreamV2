--!strict
-- Pair with InterestGroupRegression.client.lua in a separate Roblox Studio Play session.
local ReplicatedStorage = game:GetService("ReplicatedStorage")
local Players = game:GetService("Players")
local NetStream = require(ReplicatedStorage:WaitForChild("Netstream"))
assert(NetStream.GetVersion() == "4.4.0")
NetStream.Configure({HandshakeEnabled = false})
local T = NetStream.Types
local Event = NetStream.Event("__InterestEvent423", {Id = 36510, Schema = {T.U8}, Compression = false})
local State = NetStream.State("__InterestState423", {Id = 36511, Schema = {T.U16}, Compression = false})
local Ready = NetStream.Event("__InterestReady423", {Id = 36512, Schema = {T.Bool}, Compression = false})
local Ack = NetStream.Event("__InterestAck423", {Id = 36513, Schema = {T.U8}, Compression = false})
local group = NetStream.CreateInterestGroup()
local started = {}
Ready:Connect(function(player, ready)
    assert(ready == true and not started[player], "Invalid interest test start")
    started[player] = true
    assert(group:Add(player) and group:Contains(player) and group:Count() >= 1, "Interest Add failed")
    local ok1, sent1 = group:Fire(Event, 11)
    assert(ok1 and sent1 >= 1, "Interest event fanout failed")
    local ok2, sent2 = group:SetState(State, 300)
    assert(ok2 and sent2 >= 1, "Interest state fanout failed")
    assert(group:Remove(player) and not group:Contains(player), "Interest removal failed")
    local ok3, sent3 = group:Fire(Event, 99)
    assert(ok3 and sent3 == 0, "Removed player received an interest event")
    assert(group:Add(player), "Interest re-add failed")
    local ok4, sent4 = group:Fire(Event, 33)
    assert(ok4 and sent4 >= 1, "Re-added player did not receive event")
end)
Ack:Connect(function(player, received)
    assert(started[player] and received == 2, "Interest ACK invalid")
    local stats = NetStream.GetStats()
    assert(stats.InterestGroupFanouts >= 4 and stats.InterestRecipientsQueued >= 3, "Interest counters were not updated")
    assert(group:Remove(player), "Interest teardown failed")
    print("NetStream v4.4.0 interest SERVER PASS", player.UserId)
end)
Players.PlayerRemoving:Connect(function(player)
    if started[player] then started[player] = nil; group:Remove(player) end
end)
print("NetStream v4.4.0 interest server ready")
